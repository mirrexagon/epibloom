--- @meta

--- @alias TraceId uuid

--- @class tracelib
local trace = {}

--- Create a new trace and return it.
--- @param name string? # The name of the new trace. If not provided, one based on the current date and time will be used.
--- @return Trace
--- @nodiscard
function trace.new(name) end

--- Get a specific trace. Throws an error if the trace doesn't exist.
--- @param trace_id TraceId # The ID of the trace to get.
--- @return Trace
--- @nodiscard
function trace.get(trace_id) end

--- An LLM trace. Can be built up with messages and then an LLM response can be generated.
--- @class Trace
--- @field [integer] Message # The messages of the trace.
--- @field id TraceId # The UUID of the trace.
local Trace = {}

--- Start generating a message from an LLM.
--- @param backend BackendChoice
--- @param config any
function Trace.generate(backend, config) end

--- A message from or for an LLM trace.
--- @class Message
--- @field role Role Who is attributed as the message author.
--- @field content string The text of the message.
--- @field thinking string|nil LLM thinking trace that can be present on assistant messages.

--- @alias Role
--- | "system" # System instructions.
--- | "user" # Written by the user.
--- | "assistant" # Generated by an LLM.

--- @alias BackendChoice
--- | "anthropic" # https://platform.claude.com/docs
--- | "featherless" # https://featherless.ai

--- @class AnthropicConfig
--- @field integer max_tokens

return trace
